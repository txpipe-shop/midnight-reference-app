const waitForJob = async (baseUrl: string, id: string, expected: 'active' | 'ineligible') =>
  waitFor(`eligibility job ${id}`, async () => {
    const response = await fetch(`${baseUrl}/v1/jobs/${id}`);
    if (!response.ok) return false;
    const job = (await response.json()) as { status: string; errorCode?: string };
    if (job.status === 'failed') {
      throw new TerminalWaitError(`eligibility job failed: ${job.errorCode}`);
    }
    if (job.status === 'ineligible' && expected !== 'ineligible') {
      throw new TerminalWaitError(`eligibility job became ineligible: ${job.errorCode}`);
    }
    return job.status === expected ? job : false;
  });

