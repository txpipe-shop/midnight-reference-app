const withTimeout = async <T>(label: string, promise: Promise<T>): Promise<T> => {
  let timer: NodeJS.Timeout | undefined;
  try {
    return await Promise.race([
      promise,
      new Promise<never>((_, reject) => {
        timer = setTimeout(() => reject(new Error(`${label} timed out`)), TIMEOUT);
      }),
    ]);
  } finally {
    if (timer) clearTimeout(timer);
  }
};

const syncedState = (ctx: WalletContext) =>
  withTimeout(
    'wallet synchronization',
    Rx.firstValueFrom(ctx.wallet.state().pipe(Rx.filter((state) => state.isSynced)))
  );

const waitForState = <T>(
  label: string,
  ctx: WalletContext,
  predicate: (state: SyncedState) => T | false
) =>
  withTimeout(
    label,
    Rx.firstValueFrom(
      ctx.wallet.state().pipe(
        Rx.filter((state) => state.isSynced),
        Rx.map(predicate),
        Rx.filter((value): value is T => value !== false)
      )
    )
  );

const waitFor = async <T>(
  label: string,
  action: () => Promise<T | false>,
  timeout = TIMEOUT
): Promise<T> => {
  const started = Date.now();
  let lastProgress = started;
  let lastError: unknown;
  while (Date.now() - started < timeout) {
    try {
      const value = await action();
      if (value !== false) return value;
    } catch (error) {
      if (error instanceof TerminalWaitError) throw error;
      lastError = error;
    }
    if (Date.now() - lastProgress >= 15_000) {
      console.log(
        JSON.stringify({
          waiting: label,
          elapsedSeconds: Math.floor((Date.now() - started) / 1_000),
        })
      );
      lastProgress = Date.now();
    }
    await new Promise((resolve) => setTimeout(resolve, 1_000));
  }
  throw new Error(`${label} timed out${lastError ? `: ${String(lastError)}` : ''}`);
};

const scenario = async (name: string, action: () => Promise<unknown>) => {
  try {
    const detail = await action();
    report.scenarios.push({ name, status: 'passed', detail });
    console.log(JSON.stringify({ scenario: name, status: 'passed' }));
    return detail;
  } catch (error) {
    report.scenarios.push({
      name,
      status: 'failed',
      detail: error instanceof Error ? error.message : String(error),
    });
    throw error;
  }
};

const graphql = async (query: string) => {
  const response = await fetch(INDEXER, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ query }),
  });
  assert(response.ok, `indexer returned HTTP ${response.status}`);
  const result = (await response.json()) as { data?: unknown; errors?: unknown };
  assert(!result.errors, `indexer GraphQL error: ${JSON.stringify(result.errors)}`);
  return result.data;
};

const nodeRpc = async (method: string) => {
  const response = await fetch(NODE, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params: [] }),
  });
  assert(response.ok, `node returned HTTP ${response.status}`);
  const result = (await response.json()) as { result?: unknown; error?: unknown };
  assert(!result.error, `node RPC error: ${JSON.stringify(result.error)}`);
  return result.result;
};

